// Єдине джерело правди про стан програми «Власна справа».
//
// Навіщо окремий файл: до цього дати були вписані текстом у Hero,
// /umovy-prohramy, блог і пам'ятку. 1 серпня минуло — і сайт почав
// закликати «встигнути до 1 серпня» вже після того, як прийом закрився.
// Тепер фаза рахується з дати, а копірайт бере з неї готові формулювання,
// тож така розсинхронізація більше не може статися непомітно.
//
// Джерела дат: повідомлення Мінекономіки та КМУ (див. блог-пост
// onovlennya-vlasna-sprava-veresen-2026 і /umovy-prohramy).

/** Останній день прийому заявок за старою редакцією (з фіксованими сумами). */
export const OLD_RULES_LAST_DAY = new Date('2026-08-01T00:00:00Z');
/** Перший день прийому за оновленою моделлю. */
export const NEW_RULES_START = new Date('2026-09-01T00:00:00Z');

export type ProgramPhase =
  /** Стара редакція ще приймає заявки. */
  | 'old-open'
  /** Пауза між редакціями: заявки не приймають. */
  | 'pause'
  /** Працює оновлена модель. */
  | 'new-open';

export function getProgramPhase(now: Date = new Date()): ProgramPhase {
  if (now < OLD_RULES_LAST_DAY) return 'old-open';
  if (now < NEW_RULES_START) return 'pause';
  return 'new-open';
}

const fmtDate = (d: Date) =>
  d.toLocaleDateString('uk-UA', { day: 'numeric', month: 'long', timeZone: 'UTC' });

/**
 * Готові формулювання під поточну фазу. Компоненти беруть рядок звідси,
 * а не пишуть дату руками.
 */
export function getProgramStatus(now: Date = new Date()) {
  const phase = getProgramPhase(now);
  const startDate = fmtDate(NEW_RULES_START);

  if (phase === 'old-open') {
    return {
      phase,
      /** Короткий бейдж у hero. */
      badge: `Правила змінюються з ${startDate} — чинні до ${fmtDate(OLD_RULES_LAST_DAY)}`,
      /** Тон бейджа: 'warn' — оранжевий, 'info' — нейтральний. */
      tone: 'warn' as const,
      /** Заголовок блоку-попередження на /umovy-prohramy. */
      noticeTitle: 'Програма змінює модель',
      /** Один абзац пояснення поточного стану. */
      noticeText: `Чинні правила приймають заявки до ${fmtDate(OLD_RULES_LAST_DAY)}. З ${startDate} запрацює оновлена модель: замість фіксованих сум — гнучкі діапазони, нова система бонусів і окремий напрям на масштабування діючого бізнесу.`,
      /** Рядок під CTA: що робити просто зараз. */
      actionLine: 'Встигнути за чинними умовами або почекати на нові — рахуємо обидва варіанти на безкоштовному аудиті.',
      /** Заголовок секції з таблицею сум старої редакції. */
      sumsHeading: 'Скільки дають за чинними правилами',
      sumsIntro:
        'Суми, що діють у редакції з 1 січня 2026 року. Сума прив’язана не до ідеї, а до кількості офіційних робочих місць, які ви зобов’язуєтесь створити.',
    };
  }

  if (phase === 'pause') {
    return {
      phase,
      badge: `Прийом заявок відновиться ${startDate} — зараз пауза між редакціями`,
      tone: 'warn' as const,
      noticeTitle: 'Зараз прийом заявок призупинено',
      noticeText: `Стара редакція програми приймала заявки до ${fmtDate(OLD_RULES_LAST_DAY)}, оновлена стартує ${startDate}. Місяць між ними — технічна пауза: нові заявки поки не приймають. Умови нижче описують модель, за якою прийом відкриється.`,
      actionLine: `Пауза — найкращий час зібрати документи: коли прийом відкриється ${startDate}, ви подастеся у перші дні, а не почнете тоді збирати кошториси.`,
      sumsHeading: 'Скільки давала редакція, що завершилась',
      sumsIntro: `Ці суми діяли до ${fmtDate(OLD_RULES_LAST_DAY)} 2026 року. Лишаємо їх для довідки: за ними розглядають уже подані заявки, і вони показують логіку, за якою програма рахує суму — не від ідеї, а від кількості офіційних робочих місць. Діапазони, за якими відкриється прийом, — у блоці вище.`,
    };
  }

  return {
    phase,
    badge: `Діють оновлені умови програми — з ${startDate} ${NEW_RULES_START.getUTCFullYear()}`,
    tone: 'info' as const,
    noticeTitle: 'Діє оновлена модель програми',
    noticeText: `З ${startDate} ${NEW_RULES_START.getUTCFullYear()} програма працює за оновленою моделлю: гнучкі діапазони сум замість фіксованих, система бонусів і окремий напрям на масштабування діючого бізнесу.`,
    actionLine: 'Точну суму під ваш випадок рахуємо на безкоштовному аудиті — вона залежить від робочих місць, регіону, галузі та категорії заявника.',
    sumsHeading: 'Як рахувалася сума в попередній редакції',
    sumsIntro: `Довідково: суми редакції, що діяла до ${fmtDate(OLD_RULES_LAST_DAY)} 2026 року. Вони показують логіку, за якою програма прив’язує суму до кількості офіційних робочих місць. Чинні діапазони — у блоці вище.`,
  };
}
