export type BlogBlock =
  | { type: 'p'; text: string }
  | { type: 'h2'; text: string }
  | { type: 'ul'; items: string[] }
  | { type: 'callout'; text: string }
  | { type: 'links'; items: { href: string; label: string }[] }
  | { type: 'download'; href: string; label: string; text: string }
  | { type: 'table'; headers: string[]; rows: string[][] };

export interface BlogPost {
  slug: string;
  category: 'news' | 'guide';
  categoryLabel: string;
  title: string;
  metaTitle: string;
  metaDescription: string;
  excerpt: string;
  date: string; // ISO, для сортування й відображення
  /** Дата суттєвого оновлення тексту (якщо пост правили після публікації) — ISO */
  updatedDate?: string;
  readMin: number;
  body: BlogBlock[];
  relatedHref?: string;
  relatedLabel?: string;
  /**
   * Пост про подію, яка вже минула. Новини програми старіють: пост
   * «встигніть до 1 серпня» після 1 серпня починає радити неможливе.
   * Замість видалення (втратили б URL і позиції) показуємо плашку зверху
   * і бейдж у списку, а сам текст лишаємо як хроніку. Тут — що читати
   * замість нього.
   */
  outdated?: { note: string; href: string; label: string };
}

